"""
agents/summarizer.py
---------------------
Agent 4 – Plain-English Summarizer
Generates a client-friendly summary of the legal document with
key takeaways, important dates/deadlines, obligations, and disclaimers.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import List

from utils.granite import get_client

# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass
class KeyPoint:
    category: str   # e.g. "Obligation", "Deadline", "Restriction", "Right", "Risk"
    point: str


@dataclass
class SummaryResult:
    plain_english_summary: str
    key_points: List[KeyPoint] = field(default_factory=list)
    parties: List[str] = field(default_factory=list)
    document_type: str = "Legal Agreement"
    effective_date: str = "Not specified"
    term_duration: str = "Not specified"
    governing_law: str = "Not specified"
    disclaimer: str = (
        "⚠️ LEGAL DISCLAIMER: This summary is generated by an AI system for "
        "informational purposes only. It does not constitute legal advice and should "
        "not be relied upon as such. The summary may not capture all material terms. "
        "You should consult a qualified attorney before signing any legal agreement."
    )
    raw_llm_output: str = ""


# ---------------------------------------------------------------------------
# LLM prompts
# ---------------------------------------------------------------------------

_SUMMARIZER_SYSTEM_PROMPT = """
You are a plain-English legal document summarizer. Your job is to help non-lawyers
understand what they are signing. Write clearly, avoid jargon, and be honest about
what the document requires of the signing party.

Produce your output in the EXACT following format:

DOCUMENT_TYPE: <type, e.g. Non-Disclosure Agreement, Employment Contract>
PARTIES: <comma-separated list of parties>
EFFECTIVE_DATE: <date or "Not specified">
TERM_DURATION: <duration or "Not specified">
GOVERNING_LAW: <jurisdiction or "Not specified">

SUMMARY:
<3-5 paragraph plain-English overview of what this document is, what it does,
 and what the signing party is agreeing to. Use simple language a high-school
 student would understand.>

KEY_POINTS:
- OBLIGATION: <specific thing the signing party MUST do>
- OBLIGATION: <another obligation>
- RESTRICTION: <something the signing party is FORBIDDEN from doing>
- RESTRICTION: <another restriction>
- RIGHT: <a right or protection the signing party has>
- DEADLINE: <any time-bound requirement>
- RISK: <a specific risk to the signing party>

(Include as many bullet points as relevant, using the appropriate category prefix.)
"""


def _parse_summary_output(raw: str) -> dict:
    """Parse structured LLM output into a dictionary of fields."""
    result: dict = {
        "document_type": "Legal Agreement",
        "parties": [],
        "effective_date": "Not specified",
        "term_duration": "Not specified",
        "governing_law": "Not specified",
        "summary": "",
        "key_points": [],
    }

    def _field(name: str) -> str:
        m = re.search(rf"^{name}:\s*(.+)$", raw, re.MULTILINE | re.IGNORECASE)
        return m.group(1).strip() if m else ""

    val = _field("DOCUMENT_TYPE")
    if val:
        result["document_type"] = val

    parties_raw = _field("PARTIES")
    if parties_raw:
        result["parties"] = [p.strip() for p in parties_raw.split(",")]

    eff = _field("EFFECTIVE_DATE")
    if eff:
        result["effective_date"] = eff

    term = _field("TERM_DURATION")
    if term:
        result["term_duration"] = term

    gov = _field("GOVERNING_LAW")
    if gov:
        result["governing_law"] = gov

    # Extract summary block
    summary_match = re.search(r"SUMMARY:\s*\n(.*?)(?=\nKEY_POINTS:|\Z)", raw, re.DOTALL)
    if summary_match:
        result["summary"] = summary_match.group(1).strip()

    # Extract key points
    kp_match = re.search(r"KEY_POINTS:\s*\n(.*?)(?=\Z)", raw, re.DOTALL)
    if kp_match:
        kp_block = kp_match.group(1)
        key_points: List[KeyPoint] = []
        for line in kp_block.splitlines():
            line = line.strip().lstrip("-• ").strip()
            m = re.match(r"^(OBLIGATION|RESTRICTION|RIGHT|DEADLINE|RISK|WARNING):\s*(.+)$", line, re.IGNORECASE)
            if m:
                key_points.append(KeyPoint(category=m.group(1).capitalize(), point=m.group(2).strip()))
        result["key_points"] = key_points

    return result


# ---------------------------------------------------------------------------
# Heuristic metadata extraction (fallback / enrichment)
# ---------------------------------------------------------------------------

def _extract_parties_heuristic(text: str) -> List[str]:
    """Quick regex extraction of party names."""
    patterns = [
        r'between\s+([A-Z][A-Za-z\s,\.]+?)\s+\("?Disclosing Party"?\)',
        r'between\s+([A-Z][A-Za-z\s,\.]+?)\s+and\s+([A-Z][A-Za-z\s,\.]+?)\s+\(',
        r'"([A-Z][A-Za-z\s,\.]+?)"\s+\("(?:Company|Employer|Party A|Disclosing)"\)',
    ]
    parties: List[str] = []
    for pat in patterns:
        m = re.search(pat, text)
        if m:
            parties.extend(g.strip() for g in m.groups() if g)
            break
    return parties[:2]


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def summarize_document(text: str) -> SummaryResult:
    """
    Generate a plain-English summary of the legal document *text*.
    """
    client = get_client()

    user_prompt = (
        "Please summarize the following legal document in plain English, "
        "following your structured output format exactly.\n\n"
        "=== LEGAL DOCUMENT ===\n"
        f"{text[:6000]}\n"
        "=== END DOCUMENT ==="
    )

    raw_output = client.generate_with_system(_SUMMARIZER_SYSTEM_PROMPT, user_prompt)

    parsed = _parse_summary_output(raw_output)

    # Fallback to heuristic party extraction if LLM missed it
    if not parsed["parties"]:
        parsed["parties"] = _extract_parties_heuristic(text)

    # If LLM produced no structured summary (mock/offline mode), build a minimal one
    if not parsed["summary"]:
        parsed["summary"] = (
            "The AI model did not return a structured summary. "
            "This may be because IBM credentials are not configured. "
            "Please review the raw output below or configure your .env file with valid "
            "IBM_CLOUD_API_KEY, IBM_CLOUD_URL, and IBM_PROJECT_ID to enable full analysis."
        )

    return SummaryResult(
        plain_english_summary=parsed["summary"],
        key_points=parsed["key_points"],
        parties=parsed["parties"],
        document_type=parsed["document_type"],
        effective_date=parsed["effective_date"],
        term_duration=parsed["term_duration"],
        governing_law=parsed["governing_law"],
        raw_llm_output=raw_output,
    )
